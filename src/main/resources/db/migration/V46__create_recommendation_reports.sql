-- CS203-97 / CS203-6: an applicant's report that one of their impact assessments is wrong.
-- Linked to the exact assessment and the version the applicant saw, categorised, and routed
-- into the existing reviewer queue until a reviewer publishes a correction or dismisses it.
CREATE TABLE recommendation_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES policy_recommendations(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    assessment_version INTEGER NOT NULL,
    category VARCHAR(32) NOT NULL CHECK (category IN ('WRONG_SEVERITY', 'INCORRECT_INFORMATION',
        'DOES_NOT_APPLY_TO_ME', 'MISSING_INFORMATION', 'UNCLEAR', 'OTHER')),
    details VARCHAR(900) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    resolved_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    CHECK ((status = 'OPEN') = (resolved_at IS NULL))
);

-- One open report per applicant per assessment; a new one is allowed once it is handled.
CREATE UNIQUE INDEX recommendation_reports_one_open_idx
    ON recommendation_reports (assessment_id, user_id) WHERE status = 'OPEN';
CREATE INDEX recommendation_reports_open_idx
    ON recommendation_reports (assessment_id) WHERE status = 'OPEN';
