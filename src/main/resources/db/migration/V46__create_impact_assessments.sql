-- Separate processing failure from the profile-specific urgency scale.
CREATE TABLE impact_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    policy_id BIGINT NOT NULL REFERENCES policy_documents(id) ON DELETE CASCADE,
    profile_version INTEGER NOT NULL CHECK (profile_version > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('COMPLETED', 'UNAVAILABLE')),
    urgency VARCHAR(20) CHECK (urgency IN ('HIGH', 'MEDIUM', 'LOW', 'NOT_APPLICABLE')),
    confidence INTEGER CHECK (confidence BETWEEN 0 AND 100),
    summary TEXT,
    reasons JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(reasons) = 'array'),
    recommended_actions JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(recommended_actions) = 'array'),
    requires_review BOOLEAN NOT NULL DEFAULT FALSE,
    review_status VARCHAR(20) NOT NULL DEFAULT 'NOT_REQUIRED'
        CHECK (review_status IN ('NOT_REQUIRED', 'PENDING_REVIEW', 'APPROVED', 'REJECTED')),
    provider VARCHAR(100),
    model VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT impact_assessments_user_policy_profile_key UNIQUE (user_id, policy_id, profile_version),
    CONSTRAINT impact_assessments_result_check CHECK (
        (status = 'COMPLETED' AND urgency IS NOT NULL AND confidence IS NOT NULL AND summary IS NOT NULL)
        OR (status = 'UNAVAILABLE' AND urgency IS NULL AND confidence IS NULL)),
    CONSTRAINT impact_assessments_review_check CHECK (
        (requires_review AND review_status <> 'NOT_REQUIRED')
        OR (NOT requires_review AND review_status = 'NOT_REQUIRED'))
);
CREATE INDEX impact_assessments_owner_created_idx ON impact_assessments (user_id, created_at DESC);
CREATE INDEX impact_assessments_unavailable_idx ON impact_assessments (id) WHERE status = 'UNAVAILABLE';

ALTER TABLE notifications
    DROP COLUMN impact_severity,
    DROP COLUMN impact_explanation,
    DROP COLUMN impact_confidence;
