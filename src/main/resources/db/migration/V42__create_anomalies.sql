CREATE TABLE anomalies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(40) NOT NULL,
    policy_id BIGINT REFERENCES policy_documents(id) ON DELETE SET NULL,
    rule_id BIGINT REFERENCES policy_rules(id) ON DELETE SET NULL,
    source_id BIGINT REFERENCES policy_sources(id) ON DELETE SET NULL,
    details TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    correct_effective_date DATE,
    resolution_note TEXT,
    resolved_by VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT anomalies_type_check CHECK (type IN ('EFFECTIVE_DATE_CONFLICT','UNCERTAIN_RULE_LINK','MALFORMED_SOURCE_DATA','CLASSIFICATION_FAILED')),
    CONSTRAINT anomalies_status_check CHECK (status IN ('OPEN','RESOLVED','IGNORED')),
    CONSTRAINT anomalies_resolution_check CHECK ((status = 'OPEN') = (resolved_at IS NULL AND resolved_by IS NULL))
);
CREATE INDEX anomalies_open_idx ON anomalies (status, created_at DESC);
CREATE INDEX anomalies_type_idx ON anomalies (type, created_at DESC);
