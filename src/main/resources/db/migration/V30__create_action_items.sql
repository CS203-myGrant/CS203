-- CS203-4: one checklist item per recommended action of a published impact assessment.
-- Items keep their own status, so a revised assessment never resets the owner's progress.
CREATE TABLE action_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES policy_recommendations(id) ON DELETE CASCADE,
    -- Copied from the assessment. Users are anonymised, never deleted, so AccountPurgeService
    -- removes these rows itself.
    user_id BIGINT NOT NULL REFERENCES users(id),
    -- SHA-256 of the normalised action text; matches an item to the same action after a revision.
    item_key VARCHAR(64) NOT NULL,
    position INT NOT NULL,
    title VARCHAR(120) NOT NULL,
    description TEXT,
    priority VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    deadline DATE,
    completed_at TIMESTAMPTZ,
    dismissed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT action_items_assessment_key UNIQUE (assessment_id, item_key),
    CONSTRAINT action_items_priority_check CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT action_items_status_check
        CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'DISMISSED')),
    CONSTRAINT action_items_completed_at_check CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL)),
    CONSTRAINT action_items_dismissed_at_check CHECK ((status = 'DISMISSED') = (dismissed_at IS NOT NULL))
);
CREATE INDEX action_items_owner_list_idx ON action_items (user_id, status, deadline);

-- Backfill every assessment its owner can already see (ImpactVisibility), using the rules in
-- ActionItemText: ASCII whitespace is trimmed and collapsed before hashing, titles over 120
-- characters keep 117 and an ellipsis, and blank actions are skipped. The priority comes from
-- the severity and the deadline from the policy's effective date. ActionItemBackfillParityTest
-- runs this statement against the Java rules, so keep it last in the file.
INSERT INTO action_items (assessment_id, user_id, item_key, position, title, description, priority, deadline)
SELECT r.id, r.user_id,
       encode(sha256(convert_to(lower(regexp_replace(t.trimmed, '[ \t\n\f\r\v]+', ' ', 'g')), 'UTF8')), 'hex'),
       e.position,
       CASE WHEN length(t.trimmed) <= 120 THEN t.trimmed ELSE left(t.trimmed, 117) || '…' END,
       CASE WHEN length(t.trimmed) <= 120 THEN NULL ELSE t.trimmed END,
       CASE WHEN r.severity IN ('CRITICAL', 'HIGH') THEN 'HIGH'
            WHEN r.severity = 'MEDIUM' THEN 'MEDIUM' ELSE 'LOW' END,
       p.effective_date
FROM policy_recommendations r
JOIN policy_documents p ON p.id = r.policy_id
CROSS JOIN LATERAL jsonb_array_elements_text(
    CASE WHEN jsonb_typeof(r.assessment_json::jsonb -> 'recommendedActions') = 'array'
         THEN r.assessment_json::jsonb -> 'recommendedActions' ELSE '[]'::jsonb END
) WITH ORDINALITY AS e(action, position)
CROSS JOIN LATERAL (SELECT btrim(e.action, E' \t\n\f\r\x0B') AS trimmed) t
WHERE r.publication_status = 'PUBLISHED'
  AND (r.reviewed_by_human OR r.assessment_json::jsonb #>> '{evaluation,verdict}' = 'YES')
  AND t.trimmed <> ''
ORDER BY r.id, e.position
ON CONFLICT (assessment_id, item_key) DO NOTHING;
