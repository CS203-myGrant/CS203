CREATE TABLE manager_user_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT manager_user_memberships_unique_link UNIQUE (manager_id, user_id),
    CONSTRAINT manager_user_memberships_distinct_users CHECK (manager_id <> user_id)
);

CREATE INDEX manager_user_memberships_manager_idx
    ON manager_user_memberships (manager_id, created_at, user_id);
CREATE INDEX manager_user_memberships_user_idx
    ON manager_user_memberships (user_id, manager_id);
