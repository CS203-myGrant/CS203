-- A rejected draft must remain stored for audit, but never enter the applicant feed.
ALTER TABLE policy_recommendations DROP CONSTRAINT impact_publication_status_check;
ALTER TABLE policy_recommendations ADD CONSTRAINT impact_publication_status_check
    CHECK (publication_status IN ('PENDING_REVIEW', 'PUBLISHED', 'REJECTED'));

CREATE TABLE impact_review_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES policy_recommendations(id) ON DELETE CASCADE,
    reviewer_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    assessment_version INTEGER NOT NULL CHECK (assessment_version > 0),
    decision VARCHAR(10) NOT NULL CHECK (decision IN ('VERIFY', 'REJECT')),
    note VARCHAR(1000) NOT NULL CHECK (length(trim(note)) > 0),
    decided_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX impact_review_decisions_assessment_idx
    ON impact_review_decisions (assessment_id, decided_at DESC, id DESC);
