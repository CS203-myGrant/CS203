-- CS203-86: a policy rule groups the Federal Register documents of one rulemaking (proposed rule,
-- final rule, delay notices) and the news that reports on it. policy_documents is left unchanged:
-- PolicyRecommendationStore fingerprints the serialised document, so a new column there would
-- invalidate every saved assessment. Existing documents are linked by PolicyRuleBackfill at
-- startup, not here, because linking needs the same header parsing and title matching as ingestion.

-- The rule's current state. primary_stage and effective_date come from primary sources only;
-- disputed is set by a secondary (news) report of litigation or a stay and never changes the stage.
-- EFFECTIVE is not stored: it is derived when read, from the reader's test-clock date.
CREATE TABLE policy_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(1000) NOT NULL,
    primary_stage VARCHAR(30) NOT NULL,
    effective_date DATE,
    disputed BOOLEAN NOT NULL DEFAULT FALSE,
    -- Publication date of the newest primary document applied. An older document that arrives
    -- later is recorded in the history but does not move the current state.
    primary_as_of DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT policy_rules_stage_check
        CHECK (primary_stage IN ('PROPOSED', 'FINAL', 'WITHDRAWN', 'GUIDANCE', 'UNKNOWN'))
);

-- Identifiers found in a document. DOCKET and RIN are the document's own (API fields and the
-- bracketed header); FR_DOCUMENT is a Federal Register document number a news item links to.
-- Kept for unlinked news too, so a later backfill run can still link it.
CREATE TABLE policy_document_identifiers (
    policy_id BIGINT NOT NULL REFERENCES policy_documents(id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL,
    value VARCHAR(100) NOT NULL,
    PRIMARY KEY (policy_id, kind, value),
    CONSTRAINT policy_document_identifiers_kind_check CHECK (kind IN ('DOCKET', 'RIN', 'FR_DOCUMENT'))
);
CREATE INDEX policy_document_identifiers_lookup_idx ON policy_document_identifiers (kind, value);

-- Which rule a document belongs to (at most one), how it was matched, and whether a person should
-- check the match. needs_review is the minimal review marker CS203-90 can pick up later.
CREATE TABLE policy_rule_documents (
    policy_id BIGINT PRIMARY KEY REFERENCES policy_documents(id) ON DELETE CASCADE,
    rule_id BIGINT NOT NULL REFERENCES policy_rules(id) ON DELETE CASCADE,
    match_method VARCHAR(20) NOT NULL,
    confidence VARCHAR(10) NOT NULL,
    -- The identifiers or title score behind the match, for example "DOCKET ICEB-2025-0001".
    matched_on VARCHAR(500),
    needs_review BOOLEAN NOT NULL DEFAULT FALSE,
    review_reason VARCHAR(1000),
    linked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT policy_rule_documents_method_check
        CHECK (match_method IN ('NEW_RULE', 'DOCKET', 'RIN', 'DOCKET_AND_RIN', 'FR_DOCUMENT', 'TITLE')),
    CONSTRAINT policy_rule_documents_confidence_check CHECK (confidence IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT policy_rule_documents_review_check CHECK (needs_review = (review_reason IS NOT NULL))
);
CREATE INDEX policy_rule_documents_rule_idx ON policy_rule_documents (rule_id);
CREATE INDEX policy_rule_documents_review_idx ON policy_rule_documents (linked_at) WHERE needs_review;

-- Append-only stage history. Each row holds the rule's state after the source was applied and,
-- as an audit record, the state the rule held when the row was written. The source is copied so
-- provenance survives the document being deleted. dedupe_key makes a repeat insert a no-op.
-- A separate final rule in the same rulemaking (a final document on a rule already final that
-- is not about the effective date) is the exception: its row holds that final rule's own
-- effective_date, and the rule's is unchanged.
CREATE TABLE policy_rule_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT NOT NULL REFERENCES policy_rules(id) ON DELETE CASCADE,
    primary_stage VARCHAR(30) NOT NULL,
    effective_date DATE,
    disputed BOOLEAN NOT NULL,
    previous_primary_stage VARCHAR(30),
    previous_effective_date DATE,
    previous_disputed BOOLEAN,
    -- FALSE for an older document that arrived after a newer one: recorded, but not applied.
    applied BOOLEAN NOT NULL,
    -- TRUE when the row raised a PolicyChangedEvent, and so an alert.
    alerted BOOLEAN NOT NULL DEFAULT FALSE,
    -- TRUE when the source is about the effective date: its ACTION line or title names a delay,
    -- postponement, effective date or correction. On a rule already final only such a document
    -- moves the date; any other final document there is a separate final rule. Kept per row, not
    -- per decision, so the timeline can apply the same rule in publication order.
    about_effective_date BOOLEAN NOT NULL DEFAULT FALSE,
    source_policy_id BIGINT REFERENCES policy_documents(id) ON DELETE SET NULL,
    source_external_id VARCHAR(255) NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    source_url VARCHAR(2048) NOT NULL,
    source_title VARCHAR(1000) NOT NULL,
    source_agency VARCHAR(255) NOT NULL,
    -- The source's publication date; the timeline is ordered by it.
    observed_on DATE NOT NULL,
    recorded_by VARCHAR(20) NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dedupe_key VARCHAR(64) NOT NULL,
    CONSTRAINT policy_rule_history_dedupe UNIQUE (rule_id, dedupe_key),
    CONSTRAINT policy_rule_history_stage_check
        CHECK (primary_stage IN ('PROPOSED', 'FINAL', 'WITHDRAWN', 'GUIDANCE', 'UNKNOWN')),
    CONSTRAINT policy_rule_history_source_type_check CHECK (source_type IN ('PRIMARY', 'SECONDARY')),
    CONSTRAINT policy_rule_history_recorded_by_check CHECK (recorded_by IN ('INGESTION', 'BACKFILL'))
);
CREATE INDEX policy_rule_history_timeline_idx ON policy_rule_history (rule_id, observed_on, recorded_at, id);
CREATE INDEX policy_rule_history_source_idx ON policy_rule_history (source_policy_id);
