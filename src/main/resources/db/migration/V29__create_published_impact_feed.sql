UPDATE policy_recommendations SET severity = CASE assessment_json::jsonb ->> 'urgency'
    WHEN 'HIGH' THEN 'CRITICAL' WHEN 'MEDIUM' THEN 'MEDIUM'
    WHEN 'LOW' THEN 'LOW' ELSE 'INFO' END;
-- Older unverified rows must never become published just because they predate this migration.
UPDATE policy_recommendations SET publication_status = 'PENDING_REVIEW'
WHERE COALESCE(assessment_json::jsonb #>> '{evaluation,verdict}', '') <> 'YES';
CREATE INDEX impact_feed_owner_state_idx ON policy_recommendations
    (user_id, publication_status, archived_at, generated_at DESC, id DESC);

CREATE TABLE impact_assessment_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES policy_recommendations(id) ON DELETE CASCADE,
    version INTEGER NOT NULL,
    assessment_json TEXT NOT NULL,
    publication_status VARCHAR(20) NOT NULL,
    changed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (assessment_id, version)
);

CREATE FUNCTION record_impact_assessment_revision() RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO impact_assessment_revisions
        (assessment_id, version, assessment_json, publication_status, changed_by_user_id)
    VALUES (NEW.id, NEW.version, NEW.assessment_json, NEW.publication_status, NEW.reviewed_by_user_id);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER impact_revision_on_insert AFTER INSERT ON policy_recommendations
    FOR EACH ROW EXECUTE FUNCTION record_impact_assessment_revision();
CREATE TRIGGER impact_revision_on_correction
    AFTER UPDATE OF assessment_json, publication_status ON policy_recommendations
    FOR EACH ROW WHEN (OLD.assessment_json IS DISTINCT FROM NEW.assessment_json
        OR OLD.publication_status IS DISTINCT FROM NEW.publication_status)
    EXECUTE FUNCTION record_impact_assessment_revision();
INSERT INTO impact_assessment_revisions
    (assessment_id, version, assessment_json, publication_status, changed_at)
SELECT id, version, assessment_json, publication_status, generated_at
FROM policy_recommendations;

CREATE TABLE impact_archive_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES policy_recommendations(id) ON DELETE CASCADE,
    archived BOOLEAN NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE FUNCTION record_impact_archive_event() RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO impact_archive_events (assessment_id, archived)
    VALUES (NEW.id, NEW.archived_at IS NOT NULL);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER impact_archive_on_change
    AFTER UPDATE OF archived_at ON policy_recommendations
    FOR EACH ROW WHEN (OLD.archived_at IS DISTINCT FROM NEW.archived_at)
    EXECUTE FUNCTION record_impact_archive_event();
