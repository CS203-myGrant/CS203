-- CS203-91: alert emails follow the AI assessment's severity instead of the keyword flag on the
-- in-app alert. One row is one email-worthy item about one user's policy; the email outbox
-- (email_deliveries) carries these rows, with its retries and stuck-send recovery unchanged.
--
-- At most one FIRST item per user and policy, plus one ESCALATION if a later visible version of
-- the assessment is HIGH after a FIRST item below HIGH was already emailed. The unique key keeps
-- concurrent planner runs from adding a second one.
--
-- urgency is null for a change we could not assess yet; NOT_APPLICABLE is never emailed, so it
-- has no row. Title and summary are copied in when the item is planned and never change once an
-- email holds it, so a retry sends the same message under the same idempotency key.
CREATE TABLE impact_email_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    policy_id BIGINT NOT NULL REFERENCES policy_documents (id) ON DELETE CASCADE,
    notification_id BIGINT REFERENCES notifications (id) ON DELETE SET NULL,
    kind VARCHAR(12) NOT NULL,
    assessment_id BIGINT REFERENCES policy_recommendations (id) ON DELETE SET NULL,
    assessment_version INTEGER,
    urgency VARCHAR(20),
    policy_title TEXT NOT NULL,
    summary TEXT NOT NULL,
    email_delivery_id UUID REFERENCES email_deliveries (id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT impact_email_alerts_kind_valid CHECK (kind IN ('FIRST', 'ESCALATION')),
    CONSTRAINT impact_email_alerts_urgency_valid CHECK (urgency IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT impact_email_alerts_escalation_is_high
        CHECK (kind = 'FIRST' OR urgency IS NOT DISTINCT FROM 'HIGH'),
    CONSTRAINT uq_impact_email_alerts_user_policy_kind UNIQUE (user_id, policy_id, kind)
);

CREATE INDEX idx_impact_email_alerts_delivery ON impact_email_alerts (email_delivery_id);
CREATE INDEX idx_impact_email_alerts_not_emailed ON impact_email_alerts (updated_at)
    WHERE email_delivery_id IS NULL;
